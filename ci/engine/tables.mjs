// Renders the Rust protection/timing/ID tables (fm1-soc/src/spichip_tables.rs) from the Stage A reference spec,
// ci/machine/chipspec.mjs, the single source of truth. The Rust file is never edited by hand and never committed:
// build.mjs regenerates it next to the pinned upstream source. pin.json records its sha256, so a spec change
// that has not been rebuilt into the engine is caught by a test.
import { PROFILES } from "../machine/chipspec.mjs";

export function renderTables() {
  const out = [];
  out.push("// GENERATED by gen-tables.mjs from ci/machine/chipspec.mjs (Stage A datasheet spec). DO NOT EDIT BY HAND.");
  out.push("// Protection rows: [BP4, BP3, BP2, BP1, BP0] pattern (-1 = don't care) and the protected range (lo, hi), None = nothing protected.");
  out.push("");
  out.push("pub struct Row { pub pat: [i8; 5], pub range: Option<(u32, u32)> }");
  out.push("pub struct TimingUs { pub pp: u32, pub pe: u32, pub se: u32, pub be32: u32, pub be64: u32, pub ce: u32, pub wrsr: u32 }");
  out.push("pub struct Profile { pub jedec: [u8; 3], pub typical: TimingUs, pub maximum: TimingUs, pub cmp0: &'static [Row], pub cmp1: &'static [Row] }");
  out.push("");
  const rows = (name, rs) => {
    out.push(`pub static ${name}: &[Row] = &[`);
    for (const r of rs) out.push(`    Row { pat: [${r.pattern.map((c) => (c === "x" ? -1 : c)).join(", ")}], range: ${r.range ? `Some((0x${r.range.lo.toString(16).padStart(6, "0")}, 0x${r.range.hi.toString(16).padStart(6, "0")}))` : "None"} },`);
    out.push("];");
  };
  const tm = (t) => `TimingUs { pp: ${t.pp}, pe: ${t.pe}, se: ${t.se}, be32: ${t.be32}, be64: ${t.be64}, ce: ${t.ce}, wrsr: ${t.wrsr} }`;
  for (const [key, id] of [["puya", "PUYA"], ["uc25hq80", "UC25HQ80"]]) {
    const p = PROFILES[key];
    rows(`${id}_CMP0`, p.protection.cmp0);
    rows(`${id}_CMP1`, p.protection.cmp1);
    out.push(`pub static ${id}: Profile = Profile { jedec: [${p.jedec.map((b) => "0x" + b.toString(16).padStart(2, "0")).join(", ")}], typical: ${tm(p.timingUs.typical)}, maximum: ${tm(p.timingUs.maximum)}, cmp0: ${id}_CMP0, cmp1: ${id}_CMP1 };`);
    out.push("");
  }
  return out.join("\n");
}
